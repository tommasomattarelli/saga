"""Capture a saturated scenario from a real campaign in the database.

The replay producer (`scenario_build.py`) rebuilds state from an authored
transcript. This one captures state the engine already produced: the world
overlay, the active-window history and the batch summaries of a live campaign.
That is the honest source for a failure observed in real play, and the reason
its fixtures are marked `captured` rather than `derived`.

A captured state is only as faithful as the moment it was taken. When a scenario
has to move the player (a probe needs a present NPC, or the failure happened
before the current turn), pass `--position` and the fixture is marked
`reconstructed: true` — never silently.

Stimuli are authored, not captured: they belong to the scene and live in a small
YAML file next to the fixture. Recall is authored per probe for the same reason
the harness always authored it (see scenarios/README.md).

Usage:
  cd backend
  uv run python eval/capture_scenario.py --campaign <uuid> --name debug-shrine \
      --stimuli ../scratch/adr-0004-0017-eval/stimuli/shrine.yaml --out ...
"""

from __future__ import annotations

import argparse
import asyncio
import copy
import sys
import uuid
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

HEADER = (
    "# GENERATED by eval/capture_scenario.py from a live campaign.\n"
    "# Stimuli are authored in the companion file; world state is captured, not replayed.\n"
)


def _history(turns: list[Any], window: int) -> list[dict]:
    """The same pairs `_load_history` puts in the Active Window."""
    messages: list[dict] = []
    for turn in turns[-window:]:
        if not turn.narration:
            continue
        messages.append({"role": "user", "content": turn.player_action})
        messages.append({"role": "assistant", "content": turn.narration})
    return messages


def assemble(
    *,
    name: str,
    campaign: Any,
    turns: list[Any],
    summary_context: str,
    stimuli: dict,
    language: str,
    window: int,
    position: str | None = None,
    notes: str = "",
) -> dict:
    world_state = copy.deepcopy(campaign.world_state or {})
    if position:
        world_state["player_position"] = position
        world_state.setdefault("meta", {})["current_location"] = position

    return {
        "meta": {
            "name": name,
            "origin": "campaign",
            "campaign_id": str(campaign.id),
            "captured_at": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "derived": bool(summary_context),
            "reconstructed": position is not None,
            "notes": notes,
            "language": language,
            "active_window_turns": window,
        },
        "context": {
            "global_summary": campaign.global_summary or "",
            "summary_context": summary_context,
            "recall": stimuli.get("recall") or {},
        },
        "campaign": {
            "world_state": world_state,
            "world_baseline": campaign.world_baseline or {},
            "character_data": campaign.character_data or {},
            "quests": campaign.quests or {},
            "difficulty": str(campaign.difficulty),
        },
        "history": _history(turns, window),
        "probes": stimuli.get("probes") or {},
    }


async def capture(
    campaign_id: uuid.UUID,
    *,
    name: str,
    stimuli: dict,
    language: str,
    window: int,
    position: str | None,
    notes: str,
) -> dict:
    from sqlalchemy import select

    from app.ai.context import _load_batch_summaries
    from app.dependencies import get_db_context
    from app.models.campaign import Campaign
    from app.models.turn import Turn

    async with get_db_context() as db:
        campaign = (
            await db.execute(select(Campaign).where(Campaign.id == campaign_id))
        ).scalar_one()
        turns = list(
            (
                await db.execute(
                    select(Turn).where(Turn.campaign_id == campaign_id).order_by(Turn.turn_number)
                )
            )
            .scalars()
            .all()
        )
        summary_context = await _load_batch_summaries(campaign, turns[-window:], db)

        return assemble(
            name=name,
            campaign=campaign,
            turns=turns,
            summary_context=summary_context,
            stimuli=stimuli,
            language=language,
            window=window,
            position=position,
            notes=notes,
        )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--campaign", required=True, help="campaign uuid in the configured DB")
    parser.add_argument("--name", required=True, help="scenario name (written into meta)")
    parser.add_argument("--stimuli", required=True, help="YAML file with probes + recall")
    parser.add_argument("--out", required=True, help="destination .yaml")
    parser.add_argument("--language", default="en", help="expected campaign language")
    parser.add_argument("--window", type=int, default=8, help="verbatim turns in the prompt")
    parser.add_argument(
        "--position",
        help="node id to move the captured state to; marks the fixture reconstructed",
    )
    parser.add_argument("--notes", default="", help="why this capture exists")
    args = parser.parse_args()

    stimuli = yaml.safe_load(Path(args.stimuli).read_text(encoding="utf-8")) or {}
    data = asyncio.run(
        capture(
            uuid.UUID(args.campaign),
            name=args.name,
            stimuli=stimuli,
            language=args.language,
            window=args.window,
            position=args.position,
            notes=args.notes,
        )
    )

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        HEADER + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100),
        encoding="utf-8",
    )
    print(
        f"{args.name}: {len(data['history']) // 2} turns, "
        f"{len(data['probes'])} probes, reconstructed={data['meta']['reconstructed']}"
    )


if __name__ == "__main__":
    main()
